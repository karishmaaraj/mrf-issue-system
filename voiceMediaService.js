/**
 * voiceMediaService.js — Telephony Media Delivery & Temporary Audio Cache for MCC FIX HUB
 *
 * Provides temporary in-memory audio storage, cryptographically secure random media IDs,
 * path traversal protection, TTL auto-expiration, and short-lived HMAC-SHA256 signed media URLs
 * for serving synthesized TTS audio over telephony HTTP endpoints.
 *
 * STRICT SECURITY CONSTRAINTS:
 * 1. ZERO persistent disk writes — Audio buffers stored in-memory with TTL expiration.
 * 2. ZERO PII, worker PINs, tokens, or ticket context stored in media cache records.
 * 3. Cryptographically random media IDs prevent predictability and guessing attacks.
 * 4. HMAC-SHA256 signature verification with timing-safe comparison for signed media URLs.
 * 5. Path traversal checks explicitly reject arbitrary file access attempts.
 */

import crypto from 'crypto';

// In-memory media store: mediaId -> Media Record Object
const mediaStore = new Map();

/**
 * Reads Voice Media Service configuration from environment variables
 */
export function getMediaConfig() {
  const ttlMs = parseInt(process.env.VOICE_MEDIA_TTL_MS || '300000', 10); // Default 5 minutes
  const maxItems = parseInt(process.env.VOICE_MEDIA_MAX_ITEMS || '100', 10);
  const secret = process.env.VOICE_MEDIA_SECRET || process.env.VOICE_WEBHOOK_SECRET || 'mrf_voice_secret_2026';

  return {
    ttlMs: isNaN(ttlMs) || ttlMs <= 0 ? 300000 : ttlMs,
    maxItems: isNaN(maxItems) || maxItems <= 0 ? 100 : maxItems,
    secret
  };
}

/**
 * Validates mediaId format to prevent path traversal or malicious input attacks
 */
export function isValidMediaId(mediaId) {
  if (!mediaId || typeof mediaId !== 'string') return false;
  // Strictly enforce alphanumeric + underscore format (max 64 chars)
  const pattern = /^[a-zA-Z0-9_]{8,64}$/;
  if (!pattern.test(mediaId)) return false;

  // Double check for path traversal patterns explicitly
  if (mediaId.includes('..') || mediaId.includes('/') || mediaId.includes('\\') || mediaId.includes('%')) {
    return false;
  }

  return true;
}

/**
 * Cleans up expired audio records from the in-memory cache
 * @returns {number} Count of removed expired items
 */
export function cleanupExpiredVoiceAudio() {
  const now = Date.now();
  let cleanedCount = 0;

  for (const [mediaId, record] of mediaStore.entries()) {
    if (!record || now >= record.expiresAt) {
      mediaStore.delete(mediaId);
      cleanedCount++;
    }
  }

  return cleanedCount;
}

/**
 * Stores an audio Buffer in temporary in-memory cache with TTL expiration
 *
 * @param {Buffer} audioBuffer - Audio binary buffer generated by TTS
 * @param {Object} [options={}] - Options (mimeType, audioFormat, sampleRate, ttlMs)
 * @returns {Object} Stored media metadata object or failure object
 */
export function storeVoiceAudio(audioBuffer, options = {}) {
  if (!audioBuffer || !Buffer.isBuffer(audioBuffer) || audioBuffer.length === 0) {
    return {
      success: false,
      mediaId: null,
      error: 'Invalid or empty audio buffer provided'
    };
  }

  // Reasonability limit: max 10MB per audio item
  if (audioBuffer.length > 10 * 1024 * 1024) {
    return {
      success: false,
      mediaId: null,
      error: 'Audio buffer exceeds maximum allowed 10MB limit'
    };
  }

  const config = getMediaConfig();
  const ttlMs = options.ttlMs || config.ttlMs;

  // Run cleanup if store is reaching capacity limit
  if (mediaStore.size >= config.maxItems) {
    cleanupExpiredVoiceAudio();
  }

  // If still full, evict oldest entry (FIFO)
  if (mediaStore.size >= config.maxItems) {
    const oldestKey = mediaStore.keys().next().value;
    if (oldestKey) {
      mediaStore.delete(oldestKey);
    }
  }

  // Generate cryptographically secure random media ID (non-predictable)
  const randomHex = crypto.randomBytes(12).toString('hex');
  const mediaId = `med_${Date.now()}_${randomHex}`;

  const now = Date.now();
  const expiresAt = now + ttlMs;

  const record = {
    mediaId,
    audioBuffer,
    mimeType: options.mimeType || 'audio/wav',
    audioFormat: options.audioFormat || 'wav',
    sampleRate: options.sampleRate || 16000,
    createdAt: new Date(now).toISOString(),
    expiresAt
  };

  mediaStore.set(mediaId, record);

  return {
    success: true,
    mediaId,
    mimeType: record.mimeType,
    audioFormat: record.audioFormat,
    sampleRate: record.sampleRate,
    createdAt: record.createdAt,
    expiresAt
  };
}

/**
 * Retrieves a stored audio record by mediaId if valid and unexpired
 *
 * @param {string} mediaId - Media ID to retrieve
 * @returns {Object|null} Audio record object containing audioBuffer, or null
 */
export function getVoiceAudio(mediaId) {
  if (!isValidMediaId(mediaId)) return null;

  const record = mediaStore.get(mediaId);
  if (!record) return null;

  // Check expiration
  if (Date.now() >= record.expiresAt) {
    mediaStore.delete(mediaId);
    return null;
  }

  return {
    audioBuffer: record.audioBuffer,
    mimeType: record.mimeType,
    audioFormat: record.audioFormat,
    sampleRate: record.sampleRate,
    createdAt: record.createdAt,
    expiresAt: record.expiresAt
  };
}

/**
 * Explicitly deletes an audio record from in-memory cache
 * @param {string} mediaId
 */
export function deleteVoiceAudio(mediaId) {
  if (!isValidMediaId(mediaId)) return false;
  return mediaStore.delete(mediaId);
}

/**
 * Returns current media store size (for testing/monitoring)
 */
export function getMediaStoreSize() {
  return mediaStore.size;
}

/**
 * Clears all items in media store (for test suite resets)
 */
export function clearMediaStore() {
  mediaStore.clear();
}

/**
 * Generates an HMAC-SHA256 signature string for a mediaId + expiration
 */
export function calculateMediaSignature(mediaId, expiresTimestamp, secret) {
  const payload = `${mediaId}:${expiresTimestamp}`;
  return crypto
    .createHmac('sha256', secret)
    .update(payload)
    .digest('hex');
}

/**
 * Generates a short-lived signed media URL for a stored mediaId
 *
 * @param {string} mediaId - Target media ID
 * @param {string} [baseUrl=''] - Base host URL (e.g. 'https://mcc-hub.com' or '')
 * @param {number} [ttlSeconds=300] - URL validity duration in seconds (default 5 minutes)
 * @returns {string|null} Complete signed media URL string or path
 */
export function generateSignedMediaUrl(mediaId, baseUrl = '', ttlSeconds = 300) {
  if (!isValidMediaId(mediaId)) return null;

  const config = getMediaConfig();
  const expiresTimestamp = Date.now() + (ttlSeconds * 1000);
  const signature = calculateMediaSignature(mediaId, expiresTimestamp, config.secret);

  const cleanBase = baseUrl ? baseUrl.replace(/\/+$/, '') : '';
  return `${cleanBase}/api/voice/media/${mediaId}?expires=${expiresTimestamp}&signature=${signature}`;
}


/**
 * Verifies HMAC-SHA256 signature and expiration timestamp for a signed media URL request
 *
 * @param {string} mediaId - Media ID from request path
 * @param {string|number} expires - Expiration timestamp from query parameter
 * @param {string} signature - HMAC hex signature from query parameter
 * @returns {boolean} True if signature is valid, unexpired, and authentic
 */
export function verifyMediaUrlSignature(mediaId, expires, signature) {
  if (!isValidMediaId(mediaId)) return false;
  if (!expires || !signature || typeof signature !== 'string') return false;

  const expiresNum = parseInt(expires, 10);
  if (isNaN(expiresNum) || Date.now() >= expiresNum) {
    return false; // Signature expired
  }

  const config = getMediaConfig();
  const expectedSignature = calculateMediaSignature(mediaId, expiresNum, config.secret);

  try {
    const sigBuf = Buffer.from(signature, 'hex');
    const expBuf = Buffer.from(expectedSignature, 'hex');

    if (sigBuf.length !== expBuf.length || sigBuf.length === 0) {
      return false;
    }

    return crypto.timingSafeEqual(sigBuf, expBuf);
  } catch (err) {
    return false;
  }
}
